import { test, expect } from '@playwright/test'
test.use({ channel: 'chrome' })
test.skip(({ browserName }) => browserName !== 'chromium', 'Installed Chrome')
test('deck identity actions sit below two-column cards on mobile', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/ko/decks/new')

  const grid = page.locator('.planner-deck-identity-grid')
  const slot = grid.locator('.planner-deck-identity-slot').first()
  const card = slot.locator('.planner-deck-identity-card')
  await slot.getByRole('button', { name: '편성 이상', exact: true }).click()
  const modal = page.getByRole('dialog')
  await expect(modal).toBeVisible()
  await modal.getByRole('button').filter({ hasText: 'LCB 수감자' }).first().click()

  const change = slot.getByRole('button', { name: '변경 이상', exact: true })
  const formation = slot.getByRole('button', { name: '편성하기 이상', exact: true })
  const name = slot.locator('.planner-deck-identity-card__name')
  const columns = await grid.evaluate(element => getComputedStyle(element).gridTemplateColumns.split(' ').length)
  const [cardBox, changeBox, formationBox, nameBox] = await Promise.all([card.boundingBox(), change.boundingBox(), formation.boundingBox(), name.boundingBox()])

  expect(columns).toBe(2)
  expect(cardBox).not.toBeNull()
  expect(changeBox).not.toBeNull()
  expect(formationBox).not.toBeNull()
  expect(nameBox).not.toBeNull()
  expect(changeBox!.y).toBeCloseTo(cardBox!.y, 1)
  expect(changeBox!.height).toBeCloseTo(cardBox!.height, 1)
  expect(nameBox!.y + nameBox!.height).toBeLessThanOrEqual(cardBox!.y + cardBox!.height)
  expect(formationBox!.y).toBeGreaterThanOrEqual(cardBox!.y + cardBox!.height)
  await expect(change).toHaveCSS('font-size', '0px')
})

test('deck creation uses a small formation label and original EGO rank images', async ({ page }, info) => {
  test.setTimeout(90000)
  await page.goto('/ko/decks/new')
  const slot = page.locator('.planner-deck-identity-slot').first()
  const card = slot.locator('.planner-deck-identity-card')
  await card.focus()
  await slot.getByRole('button', { name: '편성 이상', exact: true }).click()
  const modal = page.getByRole('dialog')
  await expect(modal).toBeVisible()
  await modal.getByRole('button').filter({ hasText: 'LCB 수감자' }).first().click()
  await expect(modal).toHaveCount(0)
  const actions = slot.locator('.planner-deck-identity-card__overlay')
  await slot.hover()
  await expect(actions).toHaveCSS('opacity', '1')
  const form = slot.getByRole('button', { name: '편성하기 이상', exact: true })
  if (await form.count()) await form.click()
  await page.mouse.move(0, 0)
  await expect(actions).toHaveCSS('opacity', '0')
  await card.focus()
  await page.keyboard.press('Tab')
  await expect(actions).toHaveCSS('opacity', '1')
  const label = card.locator('.planner-deck-identity-card__formation')
  await expect(label).toContainText('편성')
  await expect(label.locator('img')).toHaveCount(0)
  await expect(label).toContainText('1')
  await page.screenshot({ path: info.outputPath('deck-selection.png'), fullPage: true })
  await page.getByRole('tab', { name: 'E.G.O', exact: true }).click()
  const rank = page.locator('img[src*="rank-banners/zayin.webp"]').first()
  await expect(rank).toBeVisible()
  await rank.evaluate((img: HTMLImageElement) => img.decode())
  await expect(page.locator('img[src*="icons%2Fgrade"],img[src*="icons/grade"]')).toHaveCount(0)
  await page.screenshot({ path: info.outputPath('deck-ego-ranks.png'), fullPage: true })
})
