import { test, expect, type Page } from '@playwright/test'

test.use({ channel: 'chrome' })
test.setTimeout(90000)
async function openEditor(page: Page) {
  // a site notice opens over any page once: close it whenever it shows
  const popup = page.getByRole('dialog').filter({ has: page.locator('[data-announcement-popup]') })
  await page.addLocatorHandler(popup, async () => { await popup.getByRole('button', { name: '닫기' }).last().click() })
  await page.goto('/ko/decks/new', { waitUntil:'domcontentloaded' })
  await page.getByRole('link', { name: '덱 노트', exact: true }).click()
  await expect(page.locator('.tiptap')).toBeVisible()
}
// The draft button carries its slot count ("임시 저장 0/5") and opens the five slots.
const saveDraft = /^임시 저장( \d+\/\d+)?$/
async function saveToFirstSlot(page: Page) {
  await page.getByRole('button',{name:saveDraft}).click()
  await page.getByRole('menuitem',{name:'저장',exact:true}).first().click()
}
// After a reload the editor may offer the newest autosave in a dialog; this test restores the slot it saved, so it turns the offer down.
async function restoreDraft(page: Page) {
  await expect(page.getByRole('button',{name:saveDraft})).toBeVisible()
  await page.waitForTimeout(1000)
  const offer=page.getByRole('button',{name:'버리기',exact:true})
  if (await offer.isVisible()) await offer.click()
  await page.getByRole('button',{name:saveDraft}).click()
  await page.getByRole('menuitem',{name:'불러오기',exact:true}).first().click()
}
async function insert(page: Page, name: string) {
  await page.getByRole('button', {name:'블록 삽입'}).click()
  await page.getByRole('menuitem', {name:new RegExp(name)}).click()
}

test('nested blocks survive draft reload and preview hides empty editing slots', async ({page}) => {
  await openEditor(page)
  await page.getByPlaceholder('덱 제목을 입력하세요').fill('블록 편집 검증')
  await page.locator('.tiptap').fill('/아코디언')
  await page.keyboard.press('Tab')
  await page.locator('[data-note-title]').click()
  await expect(page.locator('[data-note-title]')).toHaveAttribute('data-placeholder', /제목/)
  await page.keyboard.insertText('추천 운용')
  await page.keyboard.press('Enter')
  await page.keyboard.insertText('첫 턴에는 방어 스킬을 사용합니다.')
  await page.keyboard.press('Enter')
  await page.keyboard.insertText('/기프트')
  await page.keyboard.press('Tab')
  const giftPicker=page.getByRole('dialog',{name:'기프트 추가'})
  await giftPicker.getByRole('textbox',{name:'이름으로 검색'}).fill('시험 추출')
  const choice=giftPicker.locator('.note-direct-item').filter({hasText:'시험 추출 : 홍염살'}).first()
  await expect(choice).toBeVisible()
  await choice.click()
  await expect(page.locator('[data-note-body] .note-asset-node--gift')).toBeVisible()
  await insert(page,'테마팩')
  await expect(page.locator('[data-note-body] .note-empty-slot')).toBeVisible()
  await expect(page.getByRole('button',{name:'테마팩 선택',exact:true})).toBeVisible()
  await saveToFirstSlot(page)
  const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('limbus-deck-drafts')!).slots[0].state.description as string)
  expect(saved).toContain('!limbus-note:v1')
  expect(saved).toContain('추천 운용')
  expect(saved).not.toContain('여기에 글을')
  await page.reload({waitUntil:'domcontentloaded'})
  await restoreDraft(page)
  await page.getByRole('link', { name: '덱 노트', exact: true }).click()
  await expect(page.locator('[data-note-title]')).toContainText('추천 운용')
  await page.getByRole('button',{name:'미리보기',exact:true}).click()
  const preview=page.locator('.note-editor-preview')
  await expect(preview.locator('.note-accordion')).toBeVisible()
  await expect(preview).toContainText('첫 턴에는 방어')
  await expect(preview).toContainText('시험 추출 : 홍염살')
  await expect(preview.locator('.note-empty-slot')).toHaveCount(0)
  await expect(preview).not.toContainText('여기에 글을')
  await preview.getByRole('button',{name:'아코디언 접기 또는 펼치기'}).click()
  await expect(preview.locator('.note-accordion')).toHaveAttribute('data-open','false')
})

test('an accordion saved as closed starts closed in the editor and for readers', async ({page}) => {
  await openEditor(page)
  await page.getByPlaceholder('덱 제목을 입력하세요').fill('기본 접힘 검증')
  await page.locator('.tiptap').fill('/아코디언')
  await page.keyboard.press('Tab')
  await page.locator('[data-note-title]').click()
  await page.keyboard.insertText('접어 둔 내용')
  await page.keyboard.press('Enter')
  await page.keyboard.insertText('펼쳐야 보이는 글')
  await page.getByRole('button',{name:'기본 펼침',exact:true}).click()
  await expect(page.getByRole('button',{name:'기본 접힘',exact:true})).toHaveAttribute('aria-pressed','true')
  await expect(page.locator('[data-note-body]')).toBeHidden()
  await saveToFirstSlot(page)
  await page.reload({waitUntil:'domcontentloaded'})
  await restoreDraft(page)
  await page.getByRole('link', { name: '덱 노트', exact: true }).click()
  await expect(page.getByRole('button',{name:'기본 접힘',exact:true})).toBeVisible()
  await expect(page.locator('[data-note-body]')).toBeHidden()
  await page.getByRole('button',{name:'미리보기',exact:true}).click()
  await expect(page.locator('.note-editor-preview .note-accordion')).toHaveAttribute('data-open','false')
})

