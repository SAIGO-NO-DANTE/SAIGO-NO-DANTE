test('YouTube paste and image drop use safe embeds and the existing upload endpoint',async({page})=>{
  await openEditor(page)
  await page.locator('.tiptap').click()
  await page.locator('.tiptap').evaluate(el=>{const data=new DataTransfer();data.setData('text/plain','https://youtu.be/dQw4w9WgXcQ');el.dispatchEvent(new ClipboardEvent('paste',{bubbles:true,cancelable:true,clipboardData:data}))})
  await expect(page.locator('.note-video')).toBeVisible()
  await expect(page.locator('.note-video iframe')).toHaveCount(0)
  await page.getByRole('button',{name:'유튜브 영상 재생'}).click()
  await expect(page.locator('.note-video iframe')).toHaveAttribute('src',/youtube-nocookie.com\/embed\/dQw4w9WgXcQ/)
  const origin=await page.request.get('/api/notes/assets?kind=gift').then(r=>r.json()).then(data=>new URL(data[0].image_url).origin)
  const imageUrl=`${origin}/storage/v1/object/public/limbus-assets/notes/aaaaaaaa-bbbb-cccc-dddd-eeeeeeeeeeee.webp`
  await page.route('**/api/notes/images',route=>route.fulfill({json:{url:imageUrl}}))
  await page.locator('.tiptap').evaluate(el=>{const data=new DataTransfer();data.items.add(new File([new Uint8Array([137,80,78,71])],'guide.png',{type:'image/png'}));const box=el.getBoundingClientRect();el.dispatchEvent(new DragEvent('drop',{bubbles:true,cancelable:true,dataTransfer:data,clientX:box.x+20,clientY:box.bottom-20}))})
  await expect(page.locator('.tiptap img.note-document-image')).toHaveAttribute('src',imageUrl)
  await expect(page.locator('.note-upload')).toHaveCount(0)
  await page.route('**/api/notes/images',route=>route.fulfill({status:401,json:{error:'Unauthorized'}}))
  await page.locator('.tiptap').evaluate(el=>{const data=new DataTransfer();data.items.add(new File(['png'],'denied.png',{type:'image/png'}));el.dispatchEvent(new ClipboardEvent('paste',{bubbles:true,cancelable:true,clipboardData:data}))})
  await expect(page.getByText('로그인 후 이미지를 첨부할 수 있습니다.')).toBeVisible()
  await expect(page.locator('.tiptap img.note-document-image')).toHaveCount(1)
  await expect(page.locator('.note-upload')).toHaveCount(0)
})

test('plain keyword names become inline labels with Tab and keep surrounding text after reload',async({page})=>{
  const errors:string[]=[];page.on('console',message=>{if(message.type()==='error' && message.text().includes('flushSync'))errors.push(message.text())})
  await openEditor(page)
  await page.getByPlaceholder('덱 제목을 입력하세요').fill('키워드 검증')
  await page.locator('.tiptap').fill('적에게 화상')
  await page.keyboard.press('Tab')
  const keyword=page.locator('.tiptap .note-keyword-node')
  await expect(keyword).toContainText('화상')
  await expect(keyword.locator('img')).toBeVisible()
  await page.keyboard.insertText('5 부여')
  await expect(page.locator('.tiptap > p')).toContainText('적에게 화상 5 부여')
  await expect(keyword).toHaveCSS('display','inline')
  await saveToFirstSlot(page)
  await page.reload({waitUntil:'domcontentloaded'})
  await restoreDraft(page)
  await page.getByRole('link', { name: '덱 노트', exact: true }).click()
  await expect(page.locator('.tiptap .note-keyword-node')).toContainText('화상')
  await page.getByRole('button',{name:'미리보기',exact:true}).click()
  await expect(page.locator('.note-editor-preview p')).toContainText('적에게 화상 5 부여')
  // The reader draws the keyword as its coloured name inside the sentence (the editor also shows the icon).
  await expect(page.locator('.note-editor-preview p span').filter({hasText:/^화상$/}).first()).toBeVisible()
  expect(errors).toEqual([])
  await page.screenshot({path:'/tmp/note-keyword-inline.png'})
})
