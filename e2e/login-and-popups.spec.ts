import {test,expect} from '@playwright/test'
test.use({channel:'chrome'})
for(const width of [1440,390]) test(`login and search popup at ${width}px`,async({page})=>{
  test.setTimeout(90000)
  await page.setViewportSize({width,height:900})
  await page.emulateMedia({reducedMotion:'reduce'})
  await page.route('**/api/auth/session',route=>route.fulfill({json:{}}))
  await page.goto('/ko/login')
  // The site notice opens once per visitor after hydration and covers the page; the corner X, as the dev badge can cover the footer button.
  const notice=page.getByRole('dialog').filter({has:page.locator('[data-announcement-popup]')})
  await notice.getByRole('button',{name:'닫기'}).first().click();await expect(notice).toHaveCount(0)
  await expect(page.getByRole('heading',{name:'로그인',level:1,exact:true})).toBeVisible()
  await expect(page.getByText('관리자 로그인',{exact:true})).toHaveCount(0)
  // The wall behind the card shows identity illustrations (a fixed one only when no identity loads), never theme-pack art.
  await expect(page.locator('.login-wall-tile img').first()).toBeAttached()
  await expect(page.locator('.login-wall img[src*="theme-packs"]')).toHaveCount(0)
  // Sign-in waits for the consent to the terms and the privacy policy.
  const google=page.getByRole('button',{name:'Google로 계속하기'})
  await expect(google).toBeDisabled()
  await page.getByRole('checkbox',{name:'모두 동의'}).check()
  await expect(google).toBeEnabled()
  await expect(page.getByRole('navigation',{name:'메인 내비게이션'})).toHaveCount(0)
  // The wall's tiles below the first rows are lazy and may never load, so only the eager images are decoded.
  for(const img of await page.locator('.login-page img:visible:not([loading="lazy"])').all()) await img.evaluate((node:HTMLImageElement)=>node.decode())
  expect(await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth)).toBeLessThanOrEqual(1)
  await page.screenshot({path:`/tmp/limbus-login-${width}.png`,fullPage:true})
  await page.getByRole('link',{name:'사이트로 돌아가기'}).click()
  await expect(page).toHaveURL(/\/ko$/)
  await expect(page.locator('.login-page')).not.toBeVisible()
  await expect(page.locator('.site-navigation nav')).toBeVisible()
  await page.keyboard.press('Control+k')
  const dialog=page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  await expect(dialog.locator('.popup-search')).toHaveCSS('background-color', 'rgb(26, 21, 16)')
  // The search bar (input, clear, close) is the field's parent, laid out in a row.
  await expect(dialog.getByRole('combobox').locator('..')).toHaveCSS('display', 'flex')
  await expect(dialog.getByRole('combobox')).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  expect(await dialog.evaluate(node=>node.contains(document.activeElement))).toBe(true)
  await page.screenshot({path:`/tmp/limbus-search-${width}.png`})
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
})
